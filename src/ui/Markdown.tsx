// Markdown renderer for assistant output. react-markdown is XSS-safe by default
// (no innerHTML); remark-gfm adds tables, lists, autolinks. Links open in a new
// tab. Styling lives under `.md` in index.css.
import ReactMarkdown from 'react-markdown';
import remarkGfm from 'remark-gfm';

export function Markdown({ children }: { children: string }) {
  return (
    <div className="md">
      <ReactMarkdown
        remarkPlugins={[remarkGfm]}
        components={{
          a: ({ href, children }) => (
            <a href={href} target="_blank" rel="noopener noreferrer">
              {children}
            </a>
          ),
        }}
      >
        {children}
      </ReactMarkdown>
    </div>
  );
}
